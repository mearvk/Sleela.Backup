/* Hollow box for characters with no glyph. */
static const uint8_t k_missing[7] = { 0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F };

int ballum_header_glyph(unsigned char ch, uint8_t rows[7]) {
    if (ch < 0x20 || ch > 0x7E) return 0;
    if (rows) memcpy(rows, k_font[ch - 0x20], 7);
    return 1;
}

uint32_t ballum_header_text_width(const char *text, uint32_t scale) {
    if (!text || scale == 0) return 0;
    size_t n = strlen(text);
    if (n == 0) return 0;
    return (uint32_t)(n * 6u - 1u) * scale;
}

uint32_t ballum_header_draw_text(ballum_surface_view_t *v, int32_t x, int32_t y,
                                 const char *text, uint32_t scale, ballum_color_t fg) {
    if (!v || !text || scale == 0 || scale > 8) return 0;
    int32_t pen = x;
    for (const unsigned char *p = (const unsigned char *)text; *p; ++p) {
        const uint8_t *rows = (*p >= 0x20 && *p <= 0x7E) ? k_font[*p - 0x20] : k_missing;
        for (int r = 0; r < 7; ++r)
            for (int c = 0; c < 5; ++c)
                if (rows[r] & (1u << (4 - c))) {
                    ballum_rect_t dot = { (uint32_t)0, 0, 0, 0 };
                    int32_t dx = pen + c * (int32_t)scale, dy = y + r * (int32_t)scale;
                    if (dx < 0 || dy < 0) {
                        for (uint32_t sy = 0; sy < scale; ++sy)
                            for (uint32_t sx = 0; sx < scale; ++sx)
                                ballum_view_put(v, dx + (int32_t)sx, dy + (int32_t)sy, fg);
                    } else {
                        dot.x = (uint32_t)dx; dot.y = (uint32_t)dy; dot.width = scale; dot.height = scale;
                        ballum_view_fill(v, dot, fg);
                    }
                }
        pen += 6 * (int32_t)scale;
    }
    return ballum_header_text_width(text, scale);
}

static void header_draw(void *user, ballum_surface_view_t *v) {
    ballum_header_state_t *st = (ballum_header_state_t *)user;
    if (!st || !v) return;
    if (st->clock) {
        time_t t = st->now ? st->now(st->now_user) : time(NULL);
        struct tm tmv;
        memset(&tmv, 0, sizeof(tmv));
#if defined(_WIN32)
        if (st->utc) gmtime_s(&tmv, &t); else localtime_s(&tmv, &t);
#else
        if (st->utc ? !gmtime_r(&t, &tmv) : !localtime_r(&t, &tmv)) return;
#endif
        if (strftime(st->text, sizeof(st->text), "%Y-%m-%d %H:%M:%S", &tmv) == 0) st->text[0] = '\0';
    }
    uint32_t tw = ballum_header_text_width(st->text, st->scale);
    uint32_t th = 7u * st->scale;
    int32_t pad = 8;
    int32_t x = st->right ? (int32_t)v->w - (int32_t)tw - pad : pad;
    int32_t y = ((int32_t)v->h - (int32_t)th) / 2;
    if (x < 0) x = 0;                                   /* too long: clip on the right */
    if (y < 0) y = 0;
    ballum_header_draw_text(v, x, y, st->text, st->scale, st->fg);
}

static ballum_status_t common(ballum_header_state_t *st, uint32_t scale, ballum_color_t fg,
                              ballum_component_t *out) {
    if (!st || !out || scale < 1 || scale > 8) return BALLUM_STATUS_INVALID_ARGUMENT;
    st->scale = scale;
    st->fg = fg;
    memset(out, 0, sizeof(*out));
    out->draw = header_draw;
    out->user = st;
    return BALLUM_STATUS_OK;
}

ballum_status_t ballum_header_app_name(ballum_header_state_t *st, const char *name,
                                       uint32_t scale, ballum_color_t fg,
                                       ballum_component_t *out) {
    if (!st || !name) return BALLUM_STATUS_INVALID_ARGUMENT;
    ballum_status_t s = common(st, scale, fg, out);
    if (s != BALLUM_STATUS_OK) return s;
    memset(st->text, 0, sizeof(st->text));
    size_t i = 0;
    for (; name[i] && i + 1 < sizeof(st->text); ++i) {
        unsigned char c = (unsigned char)name[i];
        st->text[i] = (c < 0x20 || c == 0x7F) ? '?' : (char)c;
    }
    st->right = 0; st->clock = 0; st->now = NULL; st->now_user = NULL;
    out->refresh_ms = 0;
    return BALLUM_STATUS_OK;
}

ballum_status_t ballum_header_date_time(ballum_header_state_t *st, int utc,
                                        uint32_t scale, ballum_color_t fg,
                                        ballum_header_clock_fn now, void *now_user,
                                        ballum_component_t *out) {
    ballum_status_t s = common(st, scale, fg, out);
    if (s != BALLUM_STATUS_OK) return s;
    memset(st->text, 0, sizeof(st->text));
    st->right = 1; st->clock = 1; st->utc = utc ? 1 : 0;
    st->now = now; st->now_user = now_user;
    out->refresh_ms = 1000;
    return BALLUM_STATUS_OK;
}
